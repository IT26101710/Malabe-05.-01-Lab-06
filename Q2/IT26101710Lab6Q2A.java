public class IT26101710Lab6Q2A {

    public static void main(String[] args) {
        
        int count = 1;

        // Loop while count is less than or equal to 10
        while (count <= 10) {
            System.out.print(count + " ");
            count++; // Increment counter
        }
        System.out.println(); // New line at the end
    }
}